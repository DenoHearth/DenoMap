"""4K copies of OpenMap's hand-cleaned world and continent art (2026-11-07).

OpenMap draws the world (947) and the two continents (1414, 1415) from its own pictures,
Media/Textures/Forever/MapArt/<map>_<n>.tga: the game's art with the sea lettering taken out, 4 x 3
tiles of 256 px each. This makes Deno Map's three copies of each, the same way as the rest of
the pack (RealESRGAN_x4plus, the whole map at once so there are no seams, the source grain laid
back on top), into DenoMap/Maps/OpenMap/<map>_<n>.blp (4x), h/ (2x) and q/ (1x).

  py -3.12 -I openmap_art.py <OpenMap folder> <DenoMap folder> <RealESRGAN_x4plus.pth>

Runs on the CPU (about a minute per map with a recent CPU; the GPU setup of the original
pipeline is not needed for 36 tiles). Writes MapArtManifest.lua: the names it made.
"""
import os, sys
import numpy as np, torch
from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from up import with_grain, write_blp   # noqa: E402  (the pack's own grain and BLP writer)

OPENMAP, DENOMAP, MODEL = sys.argv[1], sys.argv[2], sys.argv[3]
MAPS = (947, 1414, 1415)
COLS, ROWS, T = 4, 3, 256

from spandrel import ModelLoader  # noqa: E402
net = ModelLoader().load_from_file(MODEL).model.eval()
torch.set_num_threads(max(1, (os.cpu_count() or 4) - 1))


@torch.inference_mode()
def upscale(rgb, tile=256, pad=32):
    h, w, _ = rgb.shape
    src = torch.from_numpy(np.ascontiguousarray(rgb)).permute(2, 0, 1).float().div(255).unsqueeze(0)
    src = torch.nn.functional.pad(src, (pad, pad, pad, pad), mode='reflect')
    out = torch.zeros((3, h * 4, w * 4))
    for y in range(0, h, tile):
        for x in range(0, w, tile):
            th, tw = min(tile, h - y), min(tile, w - x)
            up = net(src[:, :, y:y + th + 2 * pad, x:x + tw + 2 * pad])[0]
            out[:, y * 4:(y + th) * 4, x * 4:(x + tw) * 4] = up[:, pad * 4:(pad + th) * 4, pad * 4:(pad + tw) * 4]
            print('.', end='', flush=True)
    return (out.clamp(0, 1) * 255).round().byte().permute(1, 2, 0).numpy()


def rgba(a):
    return np.dstack([a, np.full(a.shape[:2], 255, np.uint8)])


base = os.path.join(DENOMAP, 'Maps', 'OpenMap')
for sub in ('', 'h', 'q'):
    os.makedirs(os.path.join(base, sub), exist_ok=True)
names = []
for m in MAPS:
    src = np.zeros((ROWS * T, COLS * T, 3), np.uint8)
    for n in range(1, COLS * ROWS + 1):
        r, c = divmod(n - 1, COLS)
        src[r * T:(r + 1) * T, c * T:(c + 1) * T] = np.asarray(
            Image.open(os.path.join(OPENMAP, 'Media', 'Textures', 'Forever', 'MapArt', f'{m}_{n}.tga')).convert('RGB'))
    print(f'{m}: upscaling', end='', flush=True)
    big = with_grain(upscale(src), src)
    print(' done')
    B = T * 4
    for n in range(1, COLS * ROWS + 1):
        r, c = divmod(n - 1, COLS)
        full = big[r * B:(r + 1) * B, c * B:(c + 1) * B]
        name = f'{m}_{n}'
        write_blp(os.path.join(base, name + '.blp'), rgba(full), False)
        half = np.asarray(Image.fromarray(full).resize((T * 2, T * 2), Image.LANCZOS))
        write_blp(os.path.join(base, 'h', name + '.blp'), rgba(half), False)
        write_blp(os.path.join(base, 'q', name + '.blp'), rgba(src[r * T:(r + 1) * T, c * T:(c + 1) * T]), False)
        names.append(name)

with open(os.path.join(DENOMAP, 'MapArtManifest.lua'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('-- Generated by tools/openmap_art.py: OpenMap\'s hand-cleaned map art that has a 4K copy in\n'
            '-- Maps/OpenMap (name -> width of OpenMap\'s own file).\n'
            'local ADDON, ns = ...\n\nns.openMapArt = {\n')
    for name in names:
        f.write(f'    ["{name}"] = {T},\n')
    f.write('}\n')
print('wrote', len(names), 'tiles')
