"""The sunlight colour of every zone, for the tint of the 4K minimap.

The game does not draw its minimap in the colours of the tile files: it lights it. Measured in
game on 2026-10-11 at twelve places at midday (_work/mini/watermeasure/tintfit.py), per colour
channel: seen = file x (a fixed part + a share of the zone's direct light colour - a share of
its ambient light colour), fitted over twelve places at midday and four at night, to within
0.024 on average (the numbers are in Minimap.lua).

This writes ../Lights.lua from the game's light tables (Light and LightData, read with the
foreverman db2 tool): for each world of the pack its lights (where, how far they reach, which
colour set) and the colour sets (direct light colour through the day).

    py -3 lights.py
"""
import csv
from pathlib import Path

import tinttable

BUILD = "1.60.1.70291"
DB = Path(r"C:\Users\Deniz\.claude\skills\foreverman\tools\db2cache") / BUILD
ADDON = Path(__file__).resolve().parent.parent


def main():
    worlds = sorted(int(f.name) for f in (ADDON / "Minimap").iterdir() if f.name.isdigit())
    lights = list(csv.DictReader(open(DB / "Light.csv", encoding="utf-8")))
    data = {}
    for row in csv.DictReader(open(DB / "LightData.csv", encoding="utf-8")):
        colour, around = int(row["DirectColor"]) & 0xFFFFFF, int(row["AmbientColor"]) & 0xFFFFFF
        data.setdefault(int(row["LightParamID"]), []).append(
            (int(row["Time"]), (colour >> 16) & 255, (colour >> 8) & 255, colour & 255,
             (around >> 16) & 255, (around >> 8) & 255, around & 255))
    used, lines = {}, []
    fix = tinttable.solve()          # the measured correction per light (tinttable.py, tintspots.json)

    def measured(light):
        got = fix.get(light if isinstance(light, str) else int(light["ID"]))
        return "" if not got else ", " + ", ".join(f"{v:.3f}" for v in got)
    zone_tables = tinttable.tables()[0]
    for world in worlds:
        base, base_fix, spots = None, "", []
        for light in lights:
            if int(light["ContinentID"]) != world:
                continue
            x, y, z = (float(light[f"GameCoords_{i}"]) for i in range(3))
            params = int(light["LightParamsID_0"])
            if params not in data:
                continue
            used[params] = True
            if x == 0 and y == 0 and z == 0:
                base, base_fix = params, measured(light)
            else:
                spots.append((x, y, float(light["GameFalloffStart"]), float(light["GameFalloffEnd"]), params, measured(light)))
        if base is None and not spots:
            continue
        lines.append(f"    [{world}] = {{ base = {base or 'nil'}," + (f" baseFix = {{ {base_fix[2:]} }}," if base_fix else ""))
        zones = zone_tables.get(world, {}).get("zones", [])
        if zones:
            lines.append("        zones = {")
            for key, params, outline, name in zones:
                used[params] = True
                got = fix.get(key) or (1, 1, 1)
                flat = ", ".join(f"{x:.0f}, {y:.0f}" for x, y in outline)
                lines.append(f"            {{ {params}, {got[0]:.3f}, {got[1]:.3f}, {got[2]:.3f}, {flat} }},      -- {name}")
            lines.append("        },")
        for x, y, start, end, params, extra in spots:
            lines.append(f"        {{ {x:.0f}, {y:.0f}, {start:.0f}, {end:.0f}, {params}{extra} }},")
        lines.append("    },")
    out = ["-- Generated by tools/lights.py from the game's light tables (build " + BUILD + ").",
           "-- ns.minimapLights[world] = { base = colour set of the whole world, baseFix = its measured correction,",
           "--                             zones = { { colour set, correction red, green, blue, x1, y1, x2, y2, ... (the outline) }, ... },",
           "--                             { x, y, full within, none beyond, colour set, measured correction red, green, blue (where measured) }, ... }",
           "-- Inside a zone outline its light stands in for the light of the whole world.",
           "-- ns.minimapSun[colour set] = { time in half minutes, direct light red, green, blue, ambient light red, green, blue (0-255), ... } through the day",
           "local ADDON, ns = ...", "", "ns.minimapLights = {"] + lines + ["}", "", "ns.minimapSun = {"]
    for params in sorted(used):
        keys = sorted(data[params])
        out.append(f"    [{params}] = {{ " + ", ".join(", ".join(str(n) for n in key) for key in keys) + " },")
    out.append("}")
    (ADDON / "Lights.lua").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(len(lines), "lines of lights,", len(used), "colour sets,", (ADDON / "Lights.lua").stat().st_size // 1024, "KB")


if __name__ == "__main__":
    main()
